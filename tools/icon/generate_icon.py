"""
Generates the Selfband icon from one geometry, so all copies match:
  app/src/main/res/drawable/ic_launcher_foreground.xml  (adaptive icon foreground)
  app/src/main/res/drawable/ic_launcher_monochrome.xml  (themed icon, Android 13+)
  docs/images/icon.svg                                  (full 108x108 adaptive canvas)
  docs/images/icon-512.png                              (store icon; needs Pillow)

Run from the repository root:  python tools/icon/generate_icon.py
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

BG = "1E1513"  # also @color/ic_launcher_background
CELL_COLORS = ["FF7A59", "FF9C80", "FF9C80", "FFBDA8"]
CELL = 21
GAP = 6
RADIUS = 4
# 2x2 grid of video frames inside the 66dp safe zone (21..87), centered on 54.
X0 = 54 - CELL - GAP / 2
CELLS = [(X0 + c * (CELL + GAP), X0 + r * (CELL + GAP)) for r in range(2) for c in range(2)]
# The waveform that keeps the tracks in sync, across the grid.
WAVE = [(29, 54), (35, 54), (38.5, 47), (42, 62), (46, 43), (50.5, 65), (55, 45), (59.5, 60),
        (63.5, 49), (67.5, 57), (71, 54), (79, 54)]
WAVE_WIDTH = 3
OUTLINE_WIDTH = 6.5


def rrect(x, y, w, h, r):
    return ("M%g,%g h%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%g h%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%g z"
            % (x + r, y, w - 2 * r, r, r, r, r, h - 2 * r, r, r, -r, r, -(w - 2 * r), r, r, -r, -r, -(h - 2 * r), r, r, r, -r))


WAVE_PATH = "M" + " L".join("%g,%g" % p for p in WAVE)


def vector(mono):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- SPDX-License-Identifier: GPL-3.0-or-later -->",
           "<!-- Generated by tools/icon/generate_icon.py: four video tracks in a grid, with the waveform that keeps them in sync. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp"',
           '    android:viewportWidth="108" android:viewportHeight="108">']
    for i, (x, y) in enumerate(CELLS):
        color = "#FFFFFFFF" if mono else "#FF" + CELL_COLORS[i]
        alpha = ' android:fillAlpha="0.55"' if mono else ""
        out.append('    <path android:fillColor="%s"%s android:pathData="%s" />' % (color, alpha, rrect(x, y, CELL, CELL, RADIUS)))
    if not mono:
        # Outline in the background color so the line reads over the frames.
        out.append('    <path android:strokeColor="#FF%s" android:strokeWidth="%g" android:strokeLineCap="round" '
                   'android:strokeLineJoin="round" android:fillColor="#00000000" android:pathData="%s" />' % (BG, OUTLINE_WIDTH, WAVE_PATH))
    out.append('    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="%g" android:strokeLineCap="round" '
               'android:strokeLineJoin="round" android:fillColor="#00000000" android:pathData="%s" />' % (WAVE_WIDTH, WAVE_PATH))
    out.append("</vector>")
    return "\n".join(out) + "\n"


def svg():
    out = ["<!-- SPDX-License-Identifier: GPL-3.0-or-later -->",
           '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">',
           '<rect width="108" height="108" fill="#%s"/>' % BG]
    for i, (x, y) in enumerate(CELLS):
        out.append('<path fill="#%s" d="%s"/>' % (CELL_COLORS[i], rrect(x, y, CELL, CELL, RADIUS)))
    for color, width in ((BG, OUTLINE_WIDTH), ("FFFFFF", WAVE_WIDTH)):
        out.append('<path d="%s" fill="none" stroke="#%s" stroke-width="%g" stroke-linecap="round" stroke-linejoin="round"/>'
                   % (WAVE_PATH, color, width))
    out.append("</svg>")
    return "\n".join(out) + "\n"


def png(path, size=512):
    from PIL import Image, ImageDraw

    def rgb(h):
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

    full = 768 * 4
    k = full / 108
    img = Image.new("RGB", (full, full), rgb(BG))
    d = ImageDraw.Draw(img)
    for i, (x, y) in enumerate(CELLS):
        d.rounded_rectangle((x * k, y * k, (x + CELL) * k, (y + CELL) * k), radius=RADIUS * k, fill=rgb(CELL_COLORS[i]))
    for color, width in ((rgb(BG), OUTLINE_WIDTH), ((255, 255, 255), WAVE_WIDTH)):
        pts = [(x * k, y * k) for x, y in WAVE]
        d.line(pts, fill=color, width=int(width * k), joint="curve")
        r = width * k / 2
        for x, y in (pts[0], pts[-1]):
            d.ellipse((x - r, y - r, x + r, y + r), fill=color)
    # The store icon is the part launchers show (inner 72/108), full bleed; the store applies its own mask.
    c = full * 18 // 108
    img.crop((c, c, full - c, full - c)).resize((size, size), Image.LANCZOS).save(path)


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


if __name__ == "__main__":
    write("app/src/main/res/drawable/ic_launcher_foreground.xml", vector(False))
    write("app/src/main/res/drawable/ic_launcher_monochrome.xml", vector(True))
    write("docs/images/icon.svg", svg())
    try:
        png(os.path.join(ROOT, "docs/images/icon-512.png"))
    except ImportError:
        print("Pillow not installed: icon-512.png not updated")
    print("icon written")
